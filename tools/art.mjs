// node tools/art.mjs: assets/art/config.json → cards/art.ts.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, extname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const config = JSON.parse(readFileSync(resolve(ROOT, "assets/art/config.json"), "utf8"));
const MIME = { ".webp": "image/webp", ".png": "image/png", ".jpg": "image/jpeg", ".jpeg": "image/jpeg" };
const entries = Object.entries(config).map(([name, { file, dim, dimLeft }]) => {
  const mime = MIME[extname(file).toLowerCase()];
  if (!/^[a-z][a-z0-9_]*$/.test(name) || !mime) throw new Error(`Invalid illustration: ${name}`);
  for (const opacity of [dim, dimLeft]) {
    if (!Number.isFinite(opacity) || opacity < 0 || opacity > 1) throw new Error(`Invalid opacity: ${name}`);
  }
  const bytes = readFileSync(resolve(ROOT, "assets/art", file));
  console.log(`${name}: ${bytes.length} bytes`);
  return [name, { src: `data:${mime};base64,${bytes.toString("base64")}`, dim, dimLeft }];
});
writeFileSync(resolve(ROOT, "cards/art.ts"), `// Generated by node tools/art.mjs from assets/art/config.json. Do not edit.
export type { Art };
export const ARTS: Record<string, Art> = ${JSON.stringify(Object.fromEntries(entries), null, 2)};
export const ART_NAMES: string[] = Object.keys(ARTS);
interface Art {
  src: string;
  dim: number;
  dimLeft: number;
}
`);
